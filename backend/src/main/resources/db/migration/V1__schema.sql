-- Mirrors db.js (SQLite) in PostgreSQL-compatible SQL. Timestamps are stored in UTC.
CREATE TABLE users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  phone VARCHAR(40),
  flat VARCHAR(40),
  resident_type VARCHAR(20),
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'resident',
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  consent_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE vendors(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  trade VARCHAR(100) NOT NULL,
  phone VARCHAR(40)
);

CREATE TABLE requests(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  category VARCHAR(40) NOT NULL,
  title VARCHAR(300) NOT NULL,
  description TEXT,
  photo VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  vendor_id BIGINT REFERENCES vendors(id),
  rating INTEGER,
  rating_comment TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT,
  entity VARCHAR(40) NOT NULL,
  entity_id BIGINT,
  action VARCHAR(60) NOT NULL,
  detail TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notices(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(300) NOT NULL,
  body TEXT NOT NULL,
  author_id BIGINT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE comments(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES requests(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  body TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Lease dates are plain 'YYYY-MM-DD' strings, as in the Node API.
CREATE TABLE leases(
  user_id BIGINT PRIMARY KEY REFERENCES users(id),
  start_date VARCHAR(10) NOT NULL,
  end_date VARCHAR(10) NOT NULL,
  owner_name VARCHAR(200),
  owner_phone VARCHAR(40),
  police_verified_on VARCHAR(10),
  agreement VARCHAR(300),
  parking VARCHAR(200)
);

CREATE TABLE notifications(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  message TEXT NOT NULL,
  is_read INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX notifications_user ON notifications(user_id);

CREATE TABLE emergencies(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id),
  type VARCHAR(20) NOT NULL,
  note TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at TIMESTAMP,
  resolved_by BIGINT
);

CREATE TABLE contacts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  role VARCHAR(200) NOT NULL,
  phone VARCHAR(40) NOT NULL,
  icon VARCHAR(40) NOT NULL DEFAULT 'phone'
);

CREATE TABLE gate_passes(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flat VARCHAR(40) NOT NULL,
  created_by BIGINT NOT NULL REFERENCES users(id),
  visitor_name VARCHAR(200) NOT NULL,
  purpose VARCHAR(300),
  token VARCHAR(64) NOT NULL UNIQUE,
  code VARCHAR(12) NOT NULL,
  valid_from TIMESTAMP NOT NULL,
  valid_until TIMESTAMP NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  used_at TIMESTAMP,
  used_by BIGINT
);
CREATE INDEX gate_passes_code ON gate_passes(code);

CREATE TABLE resident_tokens(
  user_id BIGINT PRIMARY KEY REFERENCES users(id),
  token VARCHAR(64) NOT NULL UNIQUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE gate_log(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR(20) NOT NULL,
  subject VARCHAR(200),
  flat VARCHAR(40),
  result VARCHAR(20) NOT NULL,
  reason VARCHAR(100),
  guard_id BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE settings(
  key VARCHAR(100) PRIMARY KEY,
  value TEXT
);

CREATE TABLE role_permissions(
  role VARCHAR(20) NOT NULL,
  permission VARCHAR(60) NOT NULL,
  allowed INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY(role, permission)
);
