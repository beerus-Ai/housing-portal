-- Tables added to db.js alongside the parking feature (vehicles, parking slots, staff register).
CREATE TABLE vehicles(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flat VARCHAR(40) NOT NULL,
  user_id BIGINT,
  plate VARCHAR(40) NOT NULL,
  plate_key VARCHAR(40) NOT NULL UNIQUE,
  type VARCHAR(20) NOT NULL DEFAULT 'car',
  make VARCHAR(100),
  color VARCHAR(40),
  sticker VARCHAR(40),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE parking_slots(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  level VARCHAR(40),
  kind VARCHAR(20) NOT NULL DEFAULT 'car',
  flat VARCHAR(40),
  vehicle_id BIGINT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE workers(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  role VARCHAR(40) NOT NULL DEFAULT 'other',
  phone VARCHAR(40),
  shift VARCHAR(40),
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  notes TEXT,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
